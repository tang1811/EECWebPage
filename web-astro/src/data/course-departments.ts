export function getDepartmentContent(slug: string): Partial<CourseDetail> {
  const entry = Object.entries(departments).find(([, department]) => department.slugs.includes(slug));
  if (!entry) return {};
  const [id, department] = entry;
  const gallery = department.images.map((filename) => {
    const photo = photoIndex[`${id}/${filename}`];
    if (!photo) throw new Error(`Missing department photo: ${id}/${filename}`);
    return photo;
  });
  return {
    overview: department.overview,
    skills: department.skills,
    careers: department.careers,
    labs: department.labs,
    learningPlan: department.learningPlan,
    gallery,
    hero: gallery[0],
    source: { url: SOURCE, pages: department.pages },
    ...department.overrides?.[slug],
  };
}
